import type { BuildConfig } from '../types/build.js';

/**
 * Parses a start command string into a JSON array for Docker's EXEC CMD form.
 * Example: "node dist/app.js" -> '["node", "dist/app.js"]'
 */
function formatCmd(command: string): string {
  const parts = command.trim().split(/\s+/);
  return JSON.stringify(parts);
}

/**
 * Formats environment variables into Docker ENV instructions.
 */
function formatEnv(envVars?: Record<string, string>): string {
  if (!envVars || Object.keys(envVars).length === 0) return '';
  return Object.entries(envVars)
    .map(([key, val]) => `ENV ${key}="${val}"`)
    .join('\n') + '\n';
}

/**
 * Generates a valid Dockerfile based on the provided build configuration.
 */
export function generateDockerfile(config: BuildConfig): string {
  const port = config.port || 3000;
  const envSection = formatEnv(config.envVars);

  switch (config.runtime) {
    case 'nodejs': {
      const version = config.runtimeVersion || '20-alpine';
      const installCmd = config.installCommand?.trim() || 'npm install';
      const buildSection = config.buildCommand?.trim()
        ? `RUN ${config.buildCommand.trim()}\n`
        : '';

      return `# Auto-generated by Relay CI/CD Platform
FROM node:${version}
WORKDIR /app

# Cache dependencies
COPY package*.json ./
RUN ${installCmd}

# Copy application source
COPY . .
${buildSection}${envSection}
EXPOSE ${port}
CMD ${formatCmd(config.startCommand)}
`.trim();
    }

    case 'python': {
      const version = config.runtimeVersion || '3.11-slim';
      const installCmd = config.installCommand?.trim() || 'pip install --no-cache-dir -r requirements.txt';

      return `# Auto-generated by Relay CI/CD Platform
FROM python:${version}
WORKDIR /app

# Install dependencies
COPY requirements*.txt ./
RUN ${installCmd}

# Copy application source
COPY . .
${envSection}
EXPOSE ${port}
CMD ${formatCmd(config.startCommand)}
`.trim();
    }

    case 'custom': {
      const baseImage = config.runtimeVersion || 'alpine:latest';
      const installSection = config.installCommand ? `RUN ${config.installCommand}\n` : '';
      const buildSection = config.buildCommand ? `RUN ${config.buildCommand}\n` : '';

      return `# Auto-generated by Relay CI/CD Platform
FROM ${baseImage}
WORKDIR /app
COPY . .
${installSection}${buildSection}${envSection}
EXPOSE ${port}
CMD ${formatCmd(config.startCommand)}
`.trim();
    }

    default:
      throw new Error(`Unsupported runtime: ${(config as any).runtime}`);
  }
}